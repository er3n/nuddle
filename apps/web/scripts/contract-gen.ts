// `mise run contract:gen` (ADR 0008): writes packages/contract/openapi.yaml from the zod schemas
// and the TypeScript client types the scenario tests use. CI regenerates and fails on a diff.
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import { stringify } from "yaml";
import { createApp, openApiDocument } from "../src/api/app";
import type { AppDeps } from "../src/api/deps";

const contractDir = new URL("../../../packages/contract/", import.meta.url);
const header = "# Generated by `mise run contract:gen` from apps/web/src/api. Do not edit.\n";

// Building the document registers routes but runs no handler, so no dependency is touched.
const deps = new Proxy({} as AppDeps, {
  get(_, prop) {
    if (prop === "e2e") return null;
    throw new Error(`contract generation must not use deps.${String(prop)}`);
  },
});

const doc = openApiDocument(await createApp(deps));
await writeFile(new URL("openapi.yaml", contractDir), header + stringify(doc, { lineWidth: 0 }));

const types = astToString(await openapiTS(JSON.parse(JSON.stringify(doc)) as never));
await writeFile(
  new URL("openapi.d.ts", contractDir),
  `// Generated by \`mise run contract:gen\` from openapi.yaml. Do not edit.\n${types}`,
);
